"""Small, explicit English/Portuguese catalog for the desktop application.

Protocol words, CSV column names and saved trigger identifiers stay in English.
Only text shown to the person using the instrument is translated.
"""

from PySide6 import QtCore


def system_language(locale_name=None):
    """Use Portuguese for any Portuguese locale; otherwise fall back to English."""
    if locale_name is None:
        locale_name = QtCore.QLocale.system().name()
    language = str(locale_name).replace("-", "_").split("_")[0].lower()
    return "pt" if language == "pt" else "en"


class Translator:
    def __init__(self, language="en"):
        self.language = language if language in ("en", "pt") else "en"

    def text(self, source, **values):
        source = DEVICE_MESSAGES.get(source, source)
        # Keep the operating system's error detail, but translate our context.
        for prefix in ("Failed to finish CSV: ", "Capture interrupted: ", "Connection: "):
            if source.startswith(prefix):
                detail = source[len(prefix):]
                heading = PORTUGUESE.get(prefix, prefix) if self.language == "pt" else prefix
                return heading + detail
        translated = PORTUGUESE.get(source, source) if self.language == "pt" else source
        return translated.format(**values) if values else translated


